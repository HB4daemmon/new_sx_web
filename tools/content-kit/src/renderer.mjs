function attributesText(attributes) {
  if (!attributes) return '未填写'
  const parts = []
  for (const [key, value] of Object.entries(attributes.flat ?? {})) {
    parts.push(`${fieldLabel(key)} +${scalarText(value)}`)
  }
  for (const [key, value] of Object.entries(attributes.percent ?? {})) {
    parts.push(`${fieldLabel(key)} +${scalarText(value * 100)}%`)
  }
  return parts.length > 0 ? parts.join('；') : '无基础属性'
}

function effectText(effect, context) {
  if (!isRecord(effect)) return '效果记录未填写'
  const parts = [
    code(effect.id),
    line(effect.text, context),
    `操作：${operationLabels[effect.operation] ?? line(effect.operation, context)}`,
    `触发：${triggerLabels[effect.trigger] ?? line(effect.trigger, context)}`,
    `目标：${structuredText(effect.target, 'target', context)}`,
    `参数：${structuredText(effect.params, 'params', context)}`,
  ]
  if (Array.isArray(effect.requires) && effect.requires.length > 0) parts.push(`前置：${list(effect.requires, context)}`)
  if (Array.isArray(effect.consumes) && effect.consumes.length > 0) parts.push(`消费：${list(effect.consumes, context)}`)
  if (Array.isArray(effect.replaces) && effect.replaces.length > 0) parts.push(`替代：${list(effect.replaces, context)}`)
  if (isRecord(effect.limit)) parts.push(`限制：${structuredText(effect.limit, 'limit', context)}`)
  return parts.join('；')
}

