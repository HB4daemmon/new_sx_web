function amountWithBasis(amount, basis) {
  const basisText = basisLabels[basis] ?? scalarText(basis)
  const amountText = ratioBases.has(basis) && typeof amount === 'number'
    ? percentageText(amount)
    : scalarText(amount)
  return `${amountText}（${basisText}）`
}

function costText(costs, context) {
  if (!Array.isArray(costs) || costs.length === 0) return '无'
  return costs.map((cost) => {
    if (!isRecord(cost)) return line(cost, context)
    if (cost.type === 'resource') {
      const resource = resourceLabels[cost.resource] ?? scalarText(cost.resource)
      const survive = cost.must_survive ? '，支付后须存活' : ''
      return `${resource} ${amountWithBasis(cost.amount, cost.basis)}${survive}`
    }
    return line(cost, context)
  }).join('；')
}

