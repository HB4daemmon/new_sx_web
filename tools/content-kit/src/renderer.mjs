function statFocusText(value) {
  if (Array.isArray(value)) {
    return value.map((item) => attributeLabels[item] ?? scalarText(item)).join('、')
  }
  if (!isRecord(value)) return attributeLabels[value] ?? structuredText(value, 'stat_focus')
  return Object.entries(value)
    .map(([key, child]) => {
      const valueText = attributeFocusKeys.has(key)
        ? statFocusText(child)
        : structuredText(child, key)
      return `${fieldLabel(key)}=${valueText}`
    })
    .join('；')
}

