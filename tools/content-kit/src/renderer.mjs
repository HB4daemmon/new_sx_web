function isRecord(value) {
  return value !== null && typeof value === 'object' && !Array.isArray(value)
}

function fieldLabel(key) {
  return fieldLabels[key] ?? key
}

function numberText(value) {
  if (!Number.isFinite(value)) return '非有限数'
  return String(value)
}

function percentageText(value) {
  if (!Number.isFinite(value)) return '非有限数'
  const percentage = Math.round(value * 10000) / 100
  return `${numberText(percentage)}%`
}

function scalarText(value) {
  if (value === null || value === undefined) return '未填写'
  if (typeof value === 'number') return numberText(value)
  if (typeof value === 'boolean') return booleanLabels[String(value)]
  if (typeof value === 'string') {
    const trimmed = value.trim()
    return trimmed === '' ? '未填写' : trimmed
  }
  return String(value)
}

function createContext(entities = []) {
  const byId = new Map()
  const talents = new Map()
  for (const entity of entities) {
    if (typeof entity?.id === 'string') byId.set(entity.id, entity)
    if (entity?.kind === 'method') {
      for (const talent of entity.talents ?? []) {
        if (typeof talent?.id === 'string') talents.set(talent.id, { ...talent, method_id: entity.id })
      }
    }
  }
  return { byId, talents }
}

function readableId(value, context) {
  if (typeof value !== 'string') return scalarText(value)
  const entity = context?.byId?.get(value)
  if (entity?.name) return `${scalarText(entity.name)}（${code(value)}）`
  const talent = context?.talents?.get(value)
  if (talent?.name) return `${scalarText(talent.name)}（${code(value)}）`
  return scalarText(value)
}

function structuredText(value, key = '', context = undefined) {
  if (value === null || value === undefined) return '未填写'
  if (Array.isArray(value)) {
    if (value.length === 0) return '无'
    return value.map((item) => structuredText(item, key, context)).join('、')
  }
  if (isRecord(value)) {
    const parts = Object.entries(value)
      .filter(([, child]) => child !== undefined)
      .map(([childKey, child]) => `${fieldLabel(childKey)}=${structuredText(child, childKey, context)}`)
    return parts.length > 0 ? parts.join('；') : '无'
  }
  if (typeof value === 'string') {
    if (context?.byId?.has(value) || context?.talents?.has(value)) return readableId(value, context)
    if (key === 'fallback' && value === 'ordinary_event') return '普通事件'
    if (key === 'resource' || key === 'fallback') return resourceLabels[value] ?? scalarText(value, key)
    if (key === 'basis') return basisLabels[value] ?? scalarText(value, key)
    if (key === 'category') return talentCategoryLabels[value] ?? scalarText(value, key)
    if (key === 'operation') return operationLabels[value] ?? scalarText(value, key)
    if (key === 'trigger') return triggerLabels[value] ?? scalarText(value, key)
    if (key === 'target') return targetLabels[value] ?? scalarText(value, key)
    if (key === 'status' || key === 'owner_status' || key === 'enemy_status') return statusLabels[value] ?? scalarText(value, key)
    if (key === 'tier') return tierLabels[value] ?? scalarText(value, key)
    if (key === 'pool') return poolLabels[value] ?? scalarText(value, key)
  }
  return scalarText(value, key)
}

function line(value, context = undefined) {
  return structuredText(value, '', context)
    .replaceAll('\n', ' ')
    .replaceAll('<br/>', '；')
    .replaceAll('<br />', '；')
    .replaceAll('<br>', '；')
    .trim()
}

function table(value, context = undefined) {
  return line(value, context).replaceAll('|', '\\|')
}

function list(values, context = undefined) {
  if (!Array.isArray(values) || values.length === 0) return '无'
  return values.map((value) => {
    if (typeof value === 'string' && (context?.byId?.has(value) || context?.talents?.has(value))) {
      return readableId(value, context)
    }
    if (kindLabels[value]) return kindLabels[value]
    return line(value, context)
  }).join('、')
}

function code(value) {
  return `\`${table(value)}\``
}

function link(label, relativePath) {
  return `[${label}](${relativePath})`
}

