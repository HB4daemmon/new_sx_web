function rewardText(rewards, context) {
  if (!Array.isArray(rewards) || rewards.length === 0) return '无'
  return rewards.map((reward) => {
    if (!isRecord(reward)) return line(reward, context)
    if (reward.type === 'artifact') return `${readableArtifact(reward.id, context)} ×${scalarText(reward.count)}`
    if (reward.type === 'resource') {
      const resource = resourceLabels[reward.resource] ?? scalarText(reward.resource)
      return `${resource} ${amountWithBasis(reward.amount, reward.basis)}`
    }
    if (reward.type === 'pool') return `${poolLabels[reward.pool] ?? scalarText(reward.pool)} ×${scalarText(reward.count)}`
    if (reward.type === 'method') return `功法 ${readableMethod(reward.id, context)}`
    if (reward.type === 'preparation') {
      return `战前准备：${fieldLabel(reward.effect)} ${amountWithBasis(reward.amount, reward.basis)}`
    }
    if (reward.type === 'swap_method') return '交换已拥有功法'
    return line(reward, context)
  }).join('；')
}

function requirementText(requirements, context) {
  if (!Array.isArray(requirements) || requirements.length === 0) return '无'
  return requirements.map((requirement) => {
    if (!isRecord(requirement)) return line(requirement, context)
    if (requirement.type === 'can_pay') return '灵石足够支付'
    if (requirement.type === 'capacity') {
      return `${readableArtifact(requirement.id, context)}可容纳 ${scalarText(requirement.count)} 层`
    }
    if (requirement.type === 'owned_artifact') {
      return `已持有 ${readableArtifact(requirement.id, context)} ×${scalarText(requirement.count)}`
    }
    if (requirement.type === 'known_method') return `已知功法 ${readableMethod(requirement.id, context)}`
    if (requirement.type === 'flag') return `已具备标记 ${scalarText(requirement.id)}=${scalarText(requirement.value)}`
    return line(requirement, context)
  }).join('；')
}

function routeNode(node, context) {
  if (typeof node === 'string') {
    if (kindLabels[node]) return `${node} ${kindLabels[node]}`
    if (context?.byId?.has(node) || context?.talents?.has(node)) return readableId(node, context)
    if (/^R-/.test(node)) return `R ${kindLabels.R}节点（${code(node)}）`
    if (/^SHOP-/.test(node)) return `S ${kindLabels.S}节点（${code(node)}）`
    return scalarText(node)
  }
  if (!isRecord(node)) return line(node, context)
  const type = node.type ?? node.kind ?? node.node_type ?? ''
  const id = node.id ?? node.enemy_id ?? node.event_id ?? ''
  const typeLabel = kindLabels[type] ? `${type} ${kindLabels[type]}` : line(type, context)
  if (!id) return typeLabel
  if (context?.byId?.has(id) || context?.talents?.has(id)) return `${typeLabel}：${readableId(id, context)}`
  return `${typeLabel}：节点（${code(id)}）`
}

function routeNodes(nodes, context) {
  if (!Array.isArray(nodes)) return '未填写'
  return nodes.map((node) => routeNode(node, context)).join(' → ')
}

function actRoutes(routes) {
  if (Array.isArray(routes)) return routes
  if (routes && typeof routes === 'object') {
    return Object.entries(routes).map(([name, value]) => (
      Array.isArray(value) ? { name, nodes: value } : { name, ...(value ?? {}) }
    ))
  }
  return []
}

