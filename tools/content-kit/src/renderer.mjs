export function renderDocuments(input) {
  const report = input && typeof input.ok === 'boolean' && input.model ? input : validateLoadedContent(input)
  assertValidContent(report)
  const entities = report.model.entities
  const context = createContext(entities)
  const rules = entities.find((entity) => entity.id === 'RULES')
  const acts = entities.filter((entity) => entity.kind === 'act').sort((left, right) => ACT_IDS.indexOf(left.id) - ACT_IDS.indexOf(right.id))
  const methods = entities.filter((entity) => entity.kind === 'method').sort((left, right) => METHOD_IDS.indexOf(left.id) - METHOD_IDS.indexOf(right.id))
  const artifacts = entities.filter((entity) => entity.kind === 'artifact').sort((left, right) => ARTIFACT_IDS.indexOf(left.id) - ARTIFACT_IDS.indexOf(right.id))
  const events = entities.filter((entity) => entity.kind === 'event').sort((left, right) => left.id.localeCompare(right.id))
  const storylines = entities.filter((entity) => entity.kind === 'storyline').sort((left, right) => STORYLINE_IDS.indexOf(left.id) - STORYLINE_IDS.indexOf(right.id))
  const enemies = entities.filter((entity) => entity.kind === 'enemy').sort((left, right) => ENEMY_IDS.indexOf(left.id) - ENEMY_IDS.indexOf(right.id))
  const pages = new Map()
  pages.set('INDEX.md', renderIndex(report))
  pages.set('RULES.md', renderRules(rules))
  pages.set('ACTS.md', renderActs(acts, context))
  for (const method of methods) pages.set(`methods/${method.id}.md`, renderMethod(method, context))
  pages.set('artifacts/COMMON.md', renderArtifacts(artifacts, 'common', context))
  pages.set('artifacts/RARE.md', renderArtifacts(artifacts, 'rare', context))
  pages.set('artifacts/LEGENDARY.md', renderArtifacts(artifacts, 'legendary', context))
  for (let act = 1; act <= 4; act += 1) pages.set(`events/ACT${act}.md`, renderEvents(events, act, context))
  for (const storyline of storylines) pages.set(`storylines/${storyline.id}.md`, renderStoryline(storyline, events, context))
  pages.set('storylines/INDEPENDENT.md', renderIndependent(events.filter((event) => event.event_type === 'core'), storylines, context))
  for (let act = 1; act <= 4; act += 1) pages.set(`enemies/ACT${act}.md`, renderEnemies(enemies, act, context))
  pages.set('enemies/FINAL.md', renderFinalEnemies(enemies, context))

  const missing = DOCUMENT_PATHS.filter((documentPath) => !pages.has(documentPath))
  if (missing.length > 0 || pages.size !== DOCUMENT_PATHS.length) {
    throw new Error(`renderer did not produce the fixed 32-page set: missing ${missing.join(', ')}`)
  }
  for (const [documentPath, text] of pages.entries()) {
    if (!text.startsWith(GENERATED_HEADER)) throw new Error(`generated header missing from ${documentPath}`)
    if (!text.endsWith('\n')) pages.set(documentPath, `${text}\n`)
  }
  return pages
}

export const renderContentPages = renderDocuments

function assertFixedPages(pages) {
  if (!(pages instanceof Map)) throw new Error('generated documents must be a Map')
  if (pages.size !== DOCUMENT_PATHS.length || DOCUMENT_PATHS.some((documentPath) => !pages.has(documentPath))) {
    throw new Error('generated documents do not match the fixed 32-page document set')
  }
  for (const relativePath of pages.keys()) {
    if (!DOCUMENT_PATH_SET.has(relativePath)) throw new Error(`unknown generated document path ${relativePath}`)
    if (typeof pages.get(relativePath) !== 'string') throw new Error(`generated document is not text: ${relativePath}`)
  }
}

async function assertNoSymlinkPath(target) {
  let current = path.resolve(target)
  while (true) {
    try {
      const stat = await lstat(current)
      if (stat.isSymbolicLink()) throw new Error(`symlink output path is not allowed: ${current}`)
    } catch (error) {
      if (error?.code !== 'ENOENT') throw error
    }
    const parent = path.dirname(current)
    if (parent === current) break
    current = parent
  }
}

function safeGeneratedPath(root, relativePath) {
  if (typeof relativePath !== 'string' || path.posix.normalize(relativePath) !== relativePath || path.posix.isAbsolute(relativePath)) {
    throw new Error(`unsafe generated document path ${relativePath}`)
  }
  const absolutePath = path.resolve(root, relativePath)
  const relative = path.relative(root, absolutePath)
  if (relative === '..' || relative.startsWith(`..${path.sep}`) || path.isAbsolute(relative)) {
    throw new Error(`unsafe generated document path ${relativePath}`)
  }
  return absolutePath
}

async function assertOutputRoot(root, { create = false } = {}) {
  await assertNoSymlinkPath(root)
  try {
    const stat = await lstat(root)
    if (!stat.isDirectory()) throw new Error(`output root is not a directory: ${root}`)
  } catch (error) {
    if (error?.code !== 'ENOENT') throw error
    if (!create) throw new Error(`output root does not exist: ${root}`)
    await mkdir(root, { recursive: true })
    await assertNoSymlinkPath(root)
  }
}

async function readOutputFile(absolutePath, relativePath) {
  await assertNoSymlinkPath(absolutePath)
  let stat
  try {
    stat = await lstat(absolutePath)
  } catch (error) {
    if (error?.code === 'ENOENT') throw new Error(`missing generated document ${relativePath}`)
    throw error
  }
  if (stat.isSymbolicLink()) throw new Error(`symlink generated document is not allowed: ${relativePath}`)
  if (!stat.isFile()) throw new Error(`generated document is not a regular file: ${relativePath}`)
  return readFile(absolutePath, 'utf8')
}

export async function writeDocuments(pages, { outputRoot = DOCS_ROOT } = {}) {
  assertFixedPages(pages)
  const root = path.resolve(outputRoot)
  await assertOutputRoot(root, { create: true })
  let index = 0
  for (const [relativePath, text] of pages.entries()) {
    const absolutePath = safeGeneratedPath(root, relativePath)
    const parent = path.dirname(absolutePath)
    await assertNoSymlinkPath(parent)
    await mkdir(parent, { recursive: true })
    await assertNoSymlinkPath(parent)
    try {
      const stat = await lstat(absolutePath)
      if (stat.isSymbolicLink()) throw new Error(`symlink generated document is not allowed: ${relativePath}`)
      if (!stat.isFile()) throw new Error(`generated document target is not a regular file: ${relativePath}`)
    } catch (error) {
      if (error?.code !== 'ENOENT') throw error
    }
    const temporary = path.join(parent, `.${path.basename(absolutePath)}.tmp-${process.pid}-${Date.now()}-${index}`)
    index += 1
    await writeFile(temporary, text, { encoding: 'utf8', flag: 'wx' })
    try {
      await assertNoSymlinkPath(temporary)
      await rename(temporary, absolutePath)
    } catch (error) {
      try {
        await unlink(temporary)
      } catch {
        // Preserve the original error; a failed cleanup must not hide it.
      }
      throw error
    }
  }
  return { outputRoot: root, paths: [...pages.keys()] }
}

export async function checkDocuments(pages, { outputRoot = DOCS_ROOT } = {}) {
  assertFixedPages(pages)
  const root = path.resolve(outputRoot)
  await assertOutputRoot(root)
  for (const relativePath of DOCUMENT_PATHS) {
    const absolutePath = safeGeneratedPath(root, relativePath)
    const actual = await readOutputFile(absolutePath, relativePath)
    const expected = pages.get(relativePath)
    if (actual !== expected) throw new Error(`generated document drift: ${relativePath}`)
  }
  return { outputRoot: root, paths: [...DOCUMENT_PATHS] }
}
