  const byId = new Map(entities.map((entity) => [entity?.id, entity]))
  const methods = METHOD_IDS.map((id) => byId.get(id)).filter(Boolean)
  const artifacts = entities.filter((entity) => entity?.kind === 'artifact')
  const events = entities.filter((entity) => entity?.kind === 'event')
  const ordinaryEvents = events.filter((event) => event.event_type === 'ordinary')
